    outs = {"sysctl": ("0\n", 0), "ss": ("0.0.0.0:22\n", 0), "iptables-save": ("*filter\n", 0)}
    for n, (o, rc) in outs.items():
        (b / n).write_text(f"#!/bin/bash\nprintf '%s' '{o}'\nexit {rc}\n")
    # R6: the real iptables-save prints a generation time and live chain counters that change between two calls (R5 run), the real `nft -s list ruleset`
    # prints one benign warning per iptables-nft table on stderr with rc 0
    (b / "iptables-save").write_text("#!/bin/bash\nprintf '# Generated by iptables-save v1.8.10 on %s\\n*nat\\n:PREROUTING ACCEPT [%s:%s]\\n-A PREROUTING -j RETURN\\nCOMMIT\\n# Completed on %s\\n' "
                                    "\"$(date +%s%N)\" \"$RANDOM\" \"$RANDOM\" \"$(date +%s%N)\"\n")
    (b / "nft").write_text("#!/bin/bash\nif [ -n \"${FAKE_NFT_RC:-}\" ] && [ \"${FAKE_NFT_RC}\" != 0 ]; then echo 'nft permission denied' >&2; exit \"$FAKE_NFT_RC\"; fi\n"
                           "if [ -n \"${FAKE_NFT_AFTER_RC:-}\" ]; then c=\"${FAKE_NFT_COUNT:-/tmp/nftcount}\"; n=$(cat \"$c\" 2>/dev/null || echo 0); echo $((n+1)) > \"$c\"; "
                           "if [ \"$n\" -ge 1 ]; then echo 'nft permission denied' >&2; exit \"$FAKE_NFT_AFTER_RC\"; fi; fi\n"
                           "echo '# Warning: table ip nat is managed by iptables-nft, do not touch!' >&2\necho 'table inet filter'\n")
    (b / "pgrep").write_text("#!/bin/bash\n[ \"${FAKE_MODE:-}\" = qemu_running ] && { echo '4242 qemu-system-arm'; exit 0; }\n[ -n \"${FAKE_PGREP_RC:-}\" ] && exit \"$FAKE_PGREP_RC\"\nexit 1\n")
    (b / "chown").write_text("#!/bin/bash\nfor a in \"$@\"; do case \"$a\" in *\"${FAKE_CHOWN_FAIL_ON:-@@never@@}\"*) echo 'chown: stub failure' >&2; exit 1;; esac; done\nexec /usr/bin/chown \"$@\"\n")
    (b / "cp").write_text("#!/bin/bash\nlast=\"${@: -1}\"; case \"$last\" in *\"${FAKE_CP_FAIL_ON:-@@never@@}\"*) echo 'cp: stub failure' >&2; exit 1;; esac\nexec /usr/bin/cp \"$@\"\n")
